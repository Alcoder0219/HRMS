import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';

import env from '../config/env.js';
import logger from '../config/logger.js';
import ApiError from '../utils/ApiError.js';
import { DOCUMENT_TYPES } from '../utils/constants.js';

/**
 * Everything that knows where an employee's files live on disk.
 *
 * One module owns the layout so the rest of the product never builds a path by
 * hand. The upload middleware, the download stream, the folder lifecycle and
 * the delete cascade all resolve through here, which is what makes "rename the
 * employee, rename the folder" a single change rather than four.
 *
 *   attachments/
 *     EMP00001/
 *       Photo/  PAN/  Aadhaar/  DrivingLicense/  Passport/
 *       Resume/  Education/  Experience/  Other/
 *
 * Nothing binary ever reaches MongoDB. The database stores the relative path
 * and the metadata; the bytes stay on the filesystem.
 */

/* -------------------------------------------------------------------------- */
/*                              Category folders                              */
/* -------------------------------------------------------------------------- */

/**
 * Document type to folder name.
 *
 * The keys reuse the existing `DOCUMENT_TYPES` enum rather than inventing a
 * parallel vocabulary -- employees already carry documents typed this way, and
 * a second enum would mean two things to keep in step. Types the Documents tab
 * does not offer still resolve, to `Other`, so an older record is never
 * unreachable.
 */
export const CATEGORY_FOLDERS = {
  [DOCUMENT_TYPES.PHOTO]: 'Photo',
  [DOCUMENT_TYPES.PAN_COPY]: 'PAN',
  [DOCUMENT_TYPES.AADHAAR_COPY]: 'Aadhaar',
  [DOCUMENT_TYPES.DRIVING_LICENSE_COPY]: 'DrivingLicense',
  [DOCUMENT_TYPES.PASSPORT_COPY]: 'Passport',
  [DOCUMENT_TYPES.RESUME]: 'Resume',
  [DOCUMENT_TYPES.EDUCATION]: 'Education',
  [DOCUMENT_TYPES.EXPERIENCE]: 'Experience',
  [DOCUMENT_TYPES.OTHER]: 'Other',
};

/** The nine folders created for every employee, in the order the tab shows them. */
export const FOLDER_NAMES = [
  'Photo',
  'PAN',
  'Aadhaar',
  'DrivingLicense',
  'Passport',
  'Resume',
  'Education',
  'Experience',
  'Other',
];

export const folderFor = (documentType) => CATEGORY_FOLDERS[documentType] ?? 'Other';

/* -------------------------------------------------------------------------- */
/*                                   Paths                                    */
/* -------------------------------------------------------------------------- */

export const ATTACHMENTS_DIR = env.attachments.dir;

/**
 * An employee code, reduced to something safe to use as a directory name.
 *
 * The code is generated by the product and is already `EMP00001`, but it is
 * still passed through here: a folder name assembled from a database value
 * without checking is exactly how a traversal gets in.
 */
const safeCode = (employeeCode) => {
  const cleaned = String(employeeCode ?? '').replace(/[^A-Za-z0-9._-]/g, '');
  if (!cleaned) throw ApiError.badRequest('That employee has no usable code for its attachment folder');
  return cleaned;
};

export const employeeFolder = (employeeCode) => path.join(ATTACHMENTS_DIR, safeCode(employeeCode));

export const categoryFolder = (employeeCode, documentType) =>
  path.join(employeeFolder(employeeCode), folderFor(documentType));

/** The value stored in MongoDB: POSIX-style and relative to the project root. */
export const relativePath = (absolutePath) =>
  path
    .relative(path.dirname(ATTACHMENTS_DIR), absolutePath)
    .split(path.sep)
    .join('/');

/**
 * Turns a stored relative path back into an absolute one, refusing anything
 * that escapes the attachments directory.
 *
 * The check is on the resolved path, not on the input string. Blacklisting
 * `..` misses encoded forms, symlinks and absolute paths; comparing the
 * resolved result against the root catches all of them.
 */
export const resolveStoredPath = (stored) => {
  if (!stored) throw ApiError.badRequest('That document has no file path');

  const withoutPrefix = String(stored).replace(/^attachments[\\/]/, '');
  const absolute = path.resolve(ATTACHMENTS_DIR, withoutPrefix);

  const root = path.resolve(ATTACHMENTS_DIR);
  if (absolute !== root && !absolute.startsWith(root + path.sep)) {
    logger.error('Blocked a path traversal attempt on an attachment', { stored });
    throw ApiError.badRequest('That file path is not valid');
  }

  return absolute;
};

/* -------------------------------------------------------------------------- */
/*                                 File names                                 */
/* -------------------------------------------------------------------------- */

/**
 * The uploaded name, kept but made safe.
 *
 * The brief asks for the original filename on disk, which is friendlier than a
 * random string when someone opens the folder directly. The name is still
 * never trusted verbatim: the directory part is dropped, the extension is
 * taken from the server-side MIME type rather than from the name, and the
 * remainder is reduced to a conservative character set. That defeats
 * `../../etc/passwd`, `photo.pdf.exe` and null-byte truncation while leaving
 * `pan_card.pdf` looking like itself.
 */
const EXTENSION_FOR_MIME = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'application/pdf': '.pdf',
};

export const safeFileName = (originalName, mimeType) => {
  const base = path
    .basename(String(originalName ?? 'file'))
    .replace(/\.[^.]*$/, '')
    .replace(/[^A-Za-z0-9._-]+/g, '_')
    .replace(/^[._-]+/, '')
    .slice(0, 80);

  const extension = EXTENSION_FOR_MIME[mimeType] ?? '';
  return `${base || 'file'}${extension}`;
};

/**
 * A name that is not already taken in the directory.
 *
 * Two `offer_letter.pdf` uploads must not silently become one file. The second
 * becomes `offer_letter (2).pdf`, which is what a desktop would do and what a
 * user expects to see.
 */
export const uniqueFileName = (directory, fileName) => {
  const extension = path.extname(fileName);
  const base = path.basename(fileName, extension);

  let candidate = fileName;
  let counter = 2;

  while (fs.existsSync(path.join(directory, candidate))) {
    candidate = `${base} (${counter})${extension}`;
    counter += 1;
  }

  return candidate;
};

/* -------------------------------------------------------------------------- */
/*                             Folder lifecycle                               */
/* -------------------------------------------------------------------------- */

/**
 * Creates the employee's folder and its nine category folders.
 *
 * Idempotent -- `recursive: true` makes a second call a no-op -- so it can be
 * called on create, on rename, and defensively before an upload without
 * anybody having to track whether it already ran.
 */
export const createEmployeeFolders = async (employeeCode) => {
  const root = employeeFolder(employeeCode);

  await fsp.mkdir(root, { recursive: true });
  await Promise.all(FOLDER_NAMES.map((name) => fsp.mkdir(path.join(root, name), { recursive: true })));

  return root;
};

/**
 * Renames the folder when an employee's code changes.
 *
 * A failure here is logged rather than thrown: the employee record has already
 * been updated by the time this runs, and rejecting the request would report a
 * failed save for a change that actually succeeded. The paths already in the
 * database still resolve, because they are stored per document.
 */
export const renameEmployeeFolder = async (fromCode, toCode) => {
  if (!fromCode || !toCode || fromCode === toCode) return false;

  const from = employeeFolder(fromCode);
  const to = employeeFolder(toCode);

  try {
    if (!fs.existsSync(from)) {
      await createEmployeeFolders(toCode);
      return false;
    }

    if (fs.existsSync(to)) {
      logger.warn('Attachment folder already exists for the new code; leaving both in place', { fromCode, toCode });
      return false;
    }

    await fsp.rename(from, to);
    logger.info('Renamed attachment folder', { fromCode, toCode });
    return true;
  } catch (error) {
    logger.error('Could not rename attachment folder', { fromCode, toCode, error: error.message });
    return false;
  }
};

/** Removes the employee's folder and everything under it. */
export const removeEmployeeFolder = async (employeeCode) => {
  const root = employeeFolder(employeeCode);

  try {
    if (!fs.existsSync(root)) return false;

    await fsp.rm(root, { recursive: true, force: true });
    logger.info('Removed attachment folder', { employeeCode });
    return true;
  } catch (error) {
    logger.error('Could not remove attachment folder', { employeeCode, error: error.message });
    return false;
  }
};

/** Deletes one stored file. Missing is treated as already gone, not as an error. */
export const removeStoredFile = async (storedPath) => {
  try {
    await fsp.unlink(resolveStoredPath(storedPath));
    return true;
  } catch (error) {
    if (error.code !== 'ENOENT') {
      logger.error('Could not delete an attachment', { storedPath, error: error.message });
    }
    return false;
  }
};

/** Rewrites the folder segment of stored paths after a rename. */
export const rewriteStoredPath = (stored, fromCode, toCode) =>
  String(stored ?? '').replace(`attachments/${fromCode}/`, `attachments/${toCode}/`);

export default {
  ATTACHMENTS_DIR,
  CATEGORY_FOLDERS,
  FOLDER_NAMES,
  folderFor,
  employeeFolder,
  categoryFolder,
  relativePath,
  resolveStoredPath,
  safeFileName,
  uniqueFileName,
  createEmployeeFolders,
  renameEmployeeFolder,
  removeEmployeeFolder,
  removeStoredFile,
  rewriteStoredPath,
};
